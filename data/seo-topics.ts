export function getSeoTopic(slug: string): SeoTopic | undefined {
  return seoTopics.find((t) => t.slug === slug)
}

export function getSeoTopicBySlugs(slugs: string[]): SeoTopic[] {
  const map = new Map(seoTopics.map((t) => [t.slug, t]))
  return slugs.map((s) => map.get(s)).filter((t): t is SeoTopic => Boolean(t))
}
